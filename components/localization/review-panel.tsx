"use client";

import { AlertTriangle, Check, Loader2, ShieldCheck, Sparkles, X } from "lucide-react";
import { useRouter } from "next/navigation";
import { useMemo, useState } from "react";
import { validateTranslation } from "@/lib/ai/validation";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { Note } from "@/components/ui/card";
import { ConfirmDialog } from "@/components/ui/confirm-dialog";
import { AmpLink } from "@/components/ui/amp-link";
import { ampLinks, type LinkBase } from "@/lib/domain/amp-links";
import type { AuditEvent, DataMode, LocalizationDiagnostic, TranslationProposal } from "@/lib/domain/types";
import { api, ApiError } from "@/lib/utils/api";
import { usd } from "@/lib/utils/format";
import { PROPOSAL_LABEL, RULE_TITLES, SEVERITY_TONE } from "./labels";

export interface ReviewFlags {
  aiTransferAllowed: boolean;
  openaiConfigured: boolean;
  model: string;
  reasoningEffort: string | null;
  writesEnabled: boolean;
  writeTokenConfigured: boolean;
  writeAllowedItemIds: string[];
  masterLocale: string;
}

interface Props {
  issue: LocalizationDiagnostic;
  proposal?: TranslationProposal;
  audit: AuditEvent[];
  mode: DataMode;
  flags: ReviewFlags;
  links: LinkBase | null;
}

const EDITABLE = ["proposed", "in_review"];

export function ReviewPanel({ issue, proposal, audit, mode, flags, links }: Props) {
  const router = useRouter();
  const [text, setText] = useState(proposal ? (proposal.editedText ?? proposal.suggestedText) : "");
  const [consent, setConsent] = useState(false);
  const [busy, setBusy] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [info, setInfo] = useState<string | null>(null);
  const [confirmWrite, setConfirmWrite] = useState(false);

  // Re-sync the editor when the server sends a different proposal revision (derived-state pattern).
  const revision = proposal ? `${proposal.id}@${proposal.updatedAt}` : "";
  const [seenRevision, setSeenRevision] = useState(revision);
  if (seenRevision !== revision) {
    setSeenRevision(revision);
    if (proposal) setText(proposal.editedText ?? proposal.suggestedText);
  }

  const validation = useMemo(() => (proposal ? validateTranslation(proposal.sourceText, text) : null), [proposal, text]);
  const editable = proposal ? EDITABLE.includes(proposal.status) : false;
  const live = mode === "live";

  const run = async (label: string, fn: () => Promise<unknown>, done?: string) => {
    setBusy(label);
    setError(null);
    setInfo(null);
    try {
      await fn();
      if (done) setInfo(done);
      router.refresh();
    } catch (e) {
      setError(e instanceof ApiError || e instanceof Error ? e.message : "Request failed");
      router.refresh();
    } finally {
      setBusy(null);
    }
  };

  const generate = () => run("generate", () => api("/api/translation/propose", "POST", { issueId: issue.id, consentToSendContent: consent }), live ? "Proposal generated by OpenAI. Review before approving." : "Simulated proposal created (no model call).");
  const review = (action: "edit" | "approve" | "reject" | "rebase", done: string) => run(action, () => api("/api/translation/review", "POST", { proposalId: proposal?.id, action, text, comment: undefined }), done);
  const applyDemo = () => run("apply", () => api("/api/translation/apply", "POST", { proposalId: proposal?.id, target: "demo" }), "Applied to the local demo dataset only. Metrics recalculated.");

  // Every condition the server enforces, shown so a disabled button is never a mystery.
  const writeBlockers = [
    !flags.writesEnabled && "ENABLE_CMS_WRITES is not true in .env.local (restart the dev server after changing it)",
    !flags.writeTokenConfigured && "AMPLIENCE_WRITE_PAT is not set (a separate write token is required)",
    !flags.writeAllowedItemIds.includes(issue.pointer.itemId) && `Content item ${issue.pointer.itemId} is not in CMS_WRITE_ALLOWED_ITEM_IDS`,
    proposal?.status !== "approved" && "Approve the proposal first",
  ].filter((x): x is string => Boolean(x));
  const dirty = proposal && editable && text !== (proposal.editedText ?? proposal.suggestedText);
  const canApprove = proposal && editable && validation && validation.blocking.length === 0 && !busy;

  return (
    <>
      <div className="flex-1 space-y-6 overflow-y-auto px-6 py-6">
        <section aria-label="Issue context" className="space-y-3">
          <div className="flex flex-wrap items-center gap-2">
            <Badge tone={SEVERITY_TONE[issue.severity]}>{issue.severity}</Badge>
            {issue.ruleIds.map((r) => <Badge key={r} tone="neutral" title={RULE_TITLES[r]}>{r} · {RULE_TITLES[r]}</Badge>)}
            {proposal && <Badge tone="info">{PROPOSAL_LABEL[proposal.status]}</Badge>}
          </div>
          <dl className="grid grid-cols-2 gap-x-4 gap-y-2 rounded-lg border border-line bg-[#fafcfb] p-3 text-[11px]">
            {[
              ["Content type", issue.contentTypeTitle],
              ["Item ID", issue.pointer.itemId],
              ["Target locale", issue.pointer.locale],
              ["Field path", issue.pointer.fieldPath],
              ["Existence", issue.existence],
              ["Completeness", issue.completeness],
              ["Freshness", issue.freshness],
              ["Publication", issue.publication],
            ].map(([k, v]) => (
              <div key={k}><dt className="text-[#8595a0]">{k}</dt><dd className="break-all font-semibold text-text">{v}</dd></div>
            ))}
          </dl>
          {links && (
            <div className="flex flex-wrap gap-x-5 gap-y-1">
              <AmpLink href={ampLinks.item(links, issue.pointer.itemId)} label={`Open the content item in Amplience (switch the form's locale to ${issue.pointer.locale})`}>Open content item</AmpLink>
              <AmpLink href={ampLinks.contentTypes(links)} label="Open content types in Amplience">Content types</AmpLink>
            </div>
          )}
          <ul className="list-disc space-y-1 pl-5 text-[11px] text-[#46606f]">
            {issue.evidence.map((e, i) => <li key={i}>{e}</li>)}
          </ul>
          <details className="text-[11px] text-muted">
            <summary className="cursor-pointer font-semibold">Why this priority ({issue.priority})</summary>
            <ul className="mt-1 list-disc pl-5">{issue.priorityRationale.map((r, i) => <li key={i}>{r}</li>)}</ul>
          </details>
        </section>

        {!issue.proposable ? (
          <Note>This is a publication finding, not a text gap. This tool never publishes; publish the content item in Dynamic Content.</Note>
        ) : (
          <>
            <section>
              <div className="field-label">Source · {flags.masterLocale}</div>
              <div className="whitespace-pre-wrap rounded-lg border border-line bg-[#fafcfb] p-4 text-[13px] leading-relaxed">{issue.sourceText}</div>
            </section>
            <section>
              <div className="field-label">Existing localized value · {issue.pointer.locale}</div>
              <div className="whitespace-pre-wrap rounded-lg border border-line bg-[#fafcfb] p-4 text-[13px] leading-relaxed">{issue.existingText || <span className="text-muted">— No value for this locale —</span>}</div>
            </section>

            <section>
              <div className="mb-2 flex items-center justify-between">
                <div className="field-label !mb-0">AI proposal · editable</div>
                {proposal && <Badge tone={proposal.provenance === "simulated" ? "demo" : "live"}>{proposal.provenance === "simulated" ? "Simulated — not a model output" : `OpenAI · ${proposal.model}`}</Badge>}
              </div>

              {!proposal || proposal.status === "not_requested" || proposal.status === "rejected" ? (
                <div className="space-y-3 rounded-lg border border-dashed border-[#cfe0dc] p-4">
                  {proposal?.status === "rejected" && <Note tone="warn">The previous proposal was rejected. This issue is back in the queue; you can request a new proposal.</Note>}
                  {live ? (
                    <>
                      <p className="text-xs leading-relaxed text-muted">
                        Generates a real proposal with OpenAI (<code>{flags.model}</code>). Only this field&apos;s source text, locale and field name are sent. No tokens, no other content.
                      </p>
                      {!flags.openaiConfigured && <Note tone="danger">OPENAI_API_KEY is not configured in .env.local.</Note>}
                      {!flags.aiTransferAllowed && <Note tone="danger">AI_SEND_CONTENT_TO_OPENAI=false — sending CMS content to OpenAI is disabled for this deployment.</Note>}
                      <p className="text-xs"><span className="font-semibold">Reasoning effort:</span> {flags.reasoningEffort ?? "model default"} <span className="text-muted">(set by OPENAI_REASONING_EFFORT in .env.local; not editable here)</span></p>
                      <label className="flex items-start gap-2 text-xs">
                        <input type="checkbox" checked={consent} onChange={(e) => setConsent(e.target.checked)} className="mt-0.5" />
                        <span>I confirm this field&apos;s text may be sent to OpenAI&apos;s API.</span>
                      </label>
                    </>
                  ) : (
                    <p className="text-xs leading-relaxed text-muted">Demo mode: the proposal is <strong>simulated</strong> from a sample phrase bank. No model is called.</p>
                  )}
                  <Button variant="primary" onClick={generate} disabled={!!busy || (live && (!consent || !flags.aiTransferAllowed || !flags.openaiConfigured))}>
                    {busy === "generate" ? <Loader2 size={14} className="animate-spin" /> : <Sparkles size={14} />} {live ? "Generate proposal with OpenAI" : "Generate simulated proposal"}
                  </Button>
                </div>
              ) : (
                <>
                  <textarea
                    value={text}
                    onChange={(e) => setText(e.target.value)}
                    onBlur={() => { if (dirty) void review("edit", "Edit saved to the audit trail."); }}
                    disabled={!editable}
                    aria-label="Editable proposed translation"
                    className="min-h-[110px] w-full resize-y rounded-lg border border-[#a2cec2] bg-[#fbfffd] p-3.5 text-[13px] leading-relaxed disabled:bg-[#f3f6f6]"
                  />
                  <div className="mt-2 space-y-1.5" aria-live="polite">
                    {validation?.blocking.map((b) => <p key={b} className="flex items-start gap-1.5 text-[11px] font-semibold text-danger"><AlertTriangle size={13} className="mt-px shrink-0" /> {b} — fix before approving</p>)}
                    {validation?.placeholderWarnings.map((w) => <p key={w} className="text-[11px] text-danger">• {w}</p>)}
                    {validation?.warnings.map((w) => <p key={w} className="text-[11px] text-[#8a5a14]">• {w}</p>)}
                    {validation && validation.blocking.length === 0 && validation.warnings.length === 0 && <p className="flex items-center gap-1.5 text-[11px] text-accent"><ShieldCheck size={13} /> Placeholders, markup and glossary terms look preserved</p>}
                    {proposal.notes.map((n, i) => <p key={i} className="text-[11px] text-muted">Note: {n}</p>)}
                  </div>
                  <dl className="mt-3 grid grid-cols-2 gap-x-4 gap-y-1.5 rounded-lg border border-line bg-[#fafcfb] p-3 text-[11px] sm:grid-cols-3">
                    {[
                      ["Model", proposal.model],
                      ["Prompt", proposal.promptVersion],
                      ["Glossary", proposal.glossaryVersion ?? "—"],
                      ["Input tokens", proposal.inputTokens?.toString() ?? "—"],
                      ["Output tokens", proposal.outputTokens?.toString() ?? "—"],
                      [proposal.actualUsd !== undefined ? "Cost (computed)" : "Cost", proposal.actualUsd !== undefined ? usd(proposal.actualUsd) : "not priced"],
                      ["Source fingerprint", proposal.sourceFingerprint.slice(0, 10)],
                      ["CMS version", proposal.cmsVersionAtProposal?.toString() ?? "—"],
                      ["Reasoning effort", proposal.provenance === "openai" ? (proposal.reasoningEffort ?? "model default") : "n/a"],
                      ["Reasoning tokens", proposal.reasoningTokens?.toString() ?? "—"],
                    ].map(([k, v]) => <div key={k}><dt className="text-[#8595a0]">{k}</dt><dd className="font-semibold">{v}</dd></div>)}
                  </dl>
                  {proposal.costNote && <p className="mt-1.5 text-[10px] text-muted">{proposal.costNote}</p>}
                  {proposal.writeError && <Note tone="danger">Write failed: {proposal.writeError}</Note>}
                </>
              )}
            </section>
          </>
        )}

        {(error || info) && (
          <div role={error ? "alert" : "status"}>
            <Note tone={error ? "danger" : "info"}>{error ?? info}</Note>
          </div>
        )}

        <section aria-label="Audit trail">
          <div className="field-label">Audit trail</div>
          {audit.length === 0 ? (
            <p className="text-xs text-muted">Issue detected by the scan. No review events yet.</p>
          ) : (
            [...audit].reverse().map((e) => (
              <div key={e.id} className="flex gap-3 border-t border-line py-3 text-xs text-[#627b89]">
                <i className="mt-1.5 h-[9px] w-[9px] shrink-0 rounded-full bg-[#83bcb0]" />
                <div>
                  <strong className="block text-[#2e4655]">{e.action}</strong>
                  <span>{new Date(e.at).toLocaleString()} · {e.actorId} · {e.previousState} → {e.nextState}{e.comment ? ` · ${e.comment}` : ""}</span>
                </div>
              </div>
            ))
          )}
        </section>
      </div>

      {issue.proposable && proposal && proposal.status !== "not_requested" && proposal.status !== "rejected" && (
        <div className="flex flex-wrap items-center gap-2.5 border-t border-line px-6 py-4">
          <Button variant="primary" onClick={() => review("approve", live ? "Approved. No Amplience write was performed." : "Approved locally. No CMS write was performed.")} disabled={!canApprove}>
            {busy === "approve" ? <Loader2 size={14} className="animate-spin" /> : <Check size={14} />} Approve proposal
          </Button>
          {mode === "demo" ? (
            <Button onClick={applyDemo} disabled={proposal.status !== "approved" || !!proposal.appliedToDemo || !!busy}>
              {proposal.appliedToDemo ? "Applied to demo" : "Apply to demo dataset"}
            </Button>
          ) : (
            <Button
              disabled={writeBlockers.length > 0 || !!busy}
              title={writeBlockers.length ? writeBlockers.join(" · ") : "Guarded save of one locale value (never publishes)"}
              onClick={() => setConfirmWrite(true)}
            >
              {writeBlockers.length ? "Save to Amplience — unavailable" : "Save to Amplience (not published)"}
            </Button>
          )}
          <Button variant="danger" onClick={() => review("reject", "Rejected. The issue returns to the queue.")} disabled={!editable || !!busy}><X size={14} /> Reject</Button>
          {mode === "live" && proposal.status === "write_failed" && (
            <div className="w-full space-y-2 rounded-lg border border-[#f0c9c5] bg-danger-soft p-3 text-[11px] text-[#8f2f2a]">
              <p><strong>Write refused:</strong> {proposal.writeError ?? "unknown error"}</p>
              <p>Nothing was changed in Amplience. If the content item changed since the proposal, sync Amplience, then re-review against the current state.</p>
              <Button size="sm" variant="primary" disabled={!!busy} onClick={() => review("rebase", "Re-review started against the current CMS state. Approve again to continue.")}>Re-review against current CMS state</Button>
            </div>
          )}
          {mode === "live" && writeBlockers.length > 0 && proposal.status !== "write_failed" && (
            <ul className="w-full list-disc pl-5 text-[10px] leading-snug text-[#8a5a14]">
              {writeBlockers.map((b) => <li key={b}>{b}</li>)}
            </ul>
          )}
          <p className="w-full text-[10px] leading-snug text-muted">
            {mode === "demo" ? "Approval stores a decision only. “Apply to demo” changes the local sample dataset. Amplience is never touched in demo mode." : "Approval stores a decision only. Live writes need every condition above, save the content item, and never publish."}
          </p>
        </div>
      )}
      {proposal && (
        <ConfirmDialog
          open={confirmWrite}
          onOpenChange={setConfirmWrite}
          title="Save this locale value to the Amplience content item?"
          description="This sets one locale's value of one field and saves the content item. It is not published."
          busy={busy === "write"}
          confirmLabel="Save item"
          rows={[
            { label: "Content item", value: `${issue.contentTypeTitle} · ${issue.title}` },
            { label: "Item ID", value: `${issue.pointer.contentTypeUid}/${issue.pointer.itemId}`, mono: true },
            { label: "Locale", value: issue.pointer.locale },
            { label: "Field", value: issue.pointer.fieldPath, mono: true },
            { label: "Current value", value: issue.existingText || "— empty —" },
            { label: "New value", value: text },
          ]}
          checks={[
            "The content item is re-read first; a changed source or item version returns a 409 and nothing is saved",
            "Only this field is merged; other content is preserved",
            "The result is read back and verified before it is marked written",
            "No publishing. The action is recorded in the audit trail",
          ]}
          onConfirm={async () => {
            await run("write", () => api("/api/translation/apply", "POST", { proposalId: proposal.id, target: "cms", confirm: true }), "Content item saved and verified by read-back. NOT published.");
            setConfirmWrite(false);
          }}
        />
      )}
    </>
  );
}
