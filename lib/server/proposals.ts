export class ServiceError extends Error {
  constructor(message: string, readonly status: number, readonly code: string) {
    super(message);
  }
}

async function save(mode: DataMode, result: { proposal: TranslationProposal; audit: AuditEvent }) {
  await store.update(mode, (d) => {
    d.proposals[result.proposal.id] = result.proposal;
    d.audit.push(result.audit);
  });
  return result.proposal;
}

export async function findProposal(mode: DataMode, proposalId: string): Promise<TranslationProposal> {
  const p = (await store.read(mode)).proposals[proposalId];
  if (!p) throw new ServiceError("Proposal not found", 404, "not_found");
  return p;
}

function step(mode: DataMode, p: TranslationProposal, ev: ReviewEvent): Promise<TranslationProposal> {
  let next: ReturnType<typeof transition>;
  try {
    next = transition(p, ev, new Date());
  } catch (err) {
    if (err instanceof TransitionError) throw new ServiceError(err.message, err.code === "invalid_state" ? 409 : 422, err.code);
    throw err;
  }
  return save(mode, next);
}

export async function stepProposal(mode: DataMode, proposalId: string, ev: ReviewEvent) {
  return step(mode, await findProposal(mode, proposalId), ev);
}

export async function proposeTranslation(
  mode: DataMode,
  issue: LocalizationDiagnostic,
  opts: { consentToSendContent: boolean; actorId: string; sourceLocale: string },
): Promise<TranslationProposal> {
  if (!issue.proposable) throw new ServiceError("This issue has no translatable text; publish the content item in Dynamic Content", 422, "not_proposable");
  const env = getEnv();
  const id = shortId("p", issue.id);
  const existing = (await store.read(mode)).proposals[id];
  if (existing && !["not_requested", "rejected", "write_failed"].includes(existing.status)) return existing; // idempotent

  if (mode === "live") {
    if (!env.AI_SEND_CONTENT_TO_OPENAI) throw new ServiceError("AI_SEND_CONTENT_TO_OPENAI=false: sending CMS content to OpenAI is not enabled for this deployment", 403, "ai_transfer_disabled");
    if (!opts.consentToSendContent) throw new ServiceError("Explicit consent to send this field's text to OpenAI is required", 403, "consent_required");
  }

  const now = new Date();
  const base: TranslationProposal = existing ?? {
    id, issueId: issue.id, unitKey: issue.unitKey, pointer: issue.pointer, status: "not_requested",
    provenance: mode === "live" ? "openai" : "simulated",
    sourceText: issue.sourceText, existingText: issue.existingText, suggestedText: "",
    model: mode === "live" ? env.OPENAI_MODEL : "simulated-fixture", promptVersion: PROMPT_VERSION, glossaryVersion: GLOSSARY_VERSION,
    sourceFingerprint: issue.sourceFingerprint, cmsVersionAtProposal: issue.cmsVersion,
    glossaryWarnings: [], placeholderWarnings: [], notes: [], updatedAt: now.toISOString(),
  };
  const fresh: TranslationProposal = { ...base, sourceText: issue.sourceText, existingText: issue.existingText, sourceFingerprint: issue.sourceFingerprint, cmsVersionAtProposal: issue.cmsVersion };
  let p = await step(mode, fresh, { type: "request" });

  try {
    if (mode === "demo") {
      const text = simulateTranslation(issue.sourceText, issue.pointer.locale);
      const v = validateTranslation(issue.sourceText, text);
      return step(mode, p, {
        type: "generated",
        patch: {
          suggestedText: text, provenance: "simulated", model: "simulated-fixture",
          placeholderWarnings: v.placeholderWarnings, glossaryWarnings: v.glossaryWarnings,
          notes: ["SIMULATED proposal from the offline sample phrase bank — not generated by a model."],
          costNote: "No model call in demo mode",
        },
      });
    }
    const result = await requestTranslation(env, {
      sourceLocale: opts.sourceLocale, targetLocale: issue.pointer.locale, contentType: issue.contentTypeTitle,
      fieldLabel: issue.fieldLabel, sourceText: issue.sourceText, existingText: issue.existingText,
    });
    const v = validateTranslation(issue.sourceText, result.output.translatedText);
    const usd = costFromUsage(env, result);
    return step(mode, p, {
      type: "generated",
      patch: {
        suggestedText: result.output.translatedText, provenance: "openai", model: result.model,
        inputTokens: result.inputTokens, outputTokens: result.outputTokens,
        reasoningTokens: result.reasoningTokens, reasoningEffort: result.reasoningEffort,
        actualUsd: usd,
        costNote: usd === undefined ? "Not priced: set OPENAI_PRICE_INPUT_PER_MTOK / OPENAI_PRICE_OUTPUT_PER_MTOK to compute cost" : "Reported token usage × configured prices",
        glossaryWarnings: [...new Set([...result.output.glossaryWarnings, ...v.glossaryWarnings])],
        placeholderWarnings: [...new Set([...result.output.placeholderWarnings, ...v.placeholderWarnings])],
        notes: [...result.output.notes, ...(result.output.confidenceLabel ? [`Model confidence label: ${result.output.confidenceLabel}`] : []), ...v.warnings],
      },
    });
  } catch (err) {
    p = await findProposal(mode, id);
    const reason = err instanceof AiError || err instanceof Error ? err.message : "Unknown error";
    await step(mode, p, { type: "generation_failed", reason });
    if (err instanceof AiError) throw new ServiceError(err.message, err.status, err.code);
    throw err;
  }
}

export async function reviewProposal(
  mode: DataMode,
  proposalId: string,
  action: "open" | "edit" | "approve" | "reject" | "rebase",
  actorId: string,
  current: LocalizationDiagnostic | undefined,
  payload: { text?: string; comment?: string },
): Promise<TranslationProposal> {
  let p = await findProposal(mode, proposalId);
  switch (action) {
    case "open":
      if (p.status === "proposed") return step(mode, p, { type: "edit", text: effectiveText(p) });
      return p;
    case "edit":
      return step(mode, p, { type: "edit", text: payload.text ?? "" });
    case "reject":
      return step(mode, p, { type: "reject", actorId, comment: payload.comment });
    case "rebase": {
      if (!current) throw new ServiceError("This issue is no longer in the current scan (it may be resolved). Sync Amplience and check again.", 409, "issue_gone");
      if (current.cmsVersion === p.cmsVersionAtProposal && current.sourceFingerprint === p.sourceFingerprint) {
        throw new ServiceError("The latest scan shows the same CMS version and source as the proposal. Sync Amplience first, then re-review.", 409, "nothing_changed");
      }
      return step(mode, p, { type: "rebase", actorId, cmsVersion: current.cmsVersion, sourceFingerprint: current.sourceFingerprint, sourceText: current.sourceText, existingText: current.existingText });
    }
    case "approve": {
      if (current?.sourceFingerprint && current.sourceFingerprint !== p.sourceFingerprint) {
        throw new ServiceError("The source text changed since this proposal was generated; request a new proposal (re-review required)", 409, "source_changed");
      }
      const text = payload.text ?? effectiveText(p);
      // SEO suggestions are free text: only emptiness blocks. Length/quality are shown as warnings, not blockers.
      const v = p.task === "seo" ? { blocking: text.trim() ? [] : ["Text is empty"] } : validateTranslation(p.sourceText, text);
      p = await step(mode, p, { type: "approve", actorId, text, blockingIssues: v.blocking });
      return p;
    }
  }
}

/** AI (or simulated, in demo) suggestion for an SEO finding. Same consent gate, audit trail and fail-closed behaviour as translation. */
export async function proposeSeoText(
  mode: DataMode,
  finding: SeoFinding,
  opts: { consentToSendContent: boolean },
): Promise<TranslationProposal> {
  if (!finding.proposable || !finding.suggestion || !finding.fieldPath || !finding.itemId) {
    throw new ServiceError("This finding has no text suggestion (it needs a schema or editorial change)", 422, "not_proposable");
  }
  const env = getEnv();
  const id = shortId("p", finding.id);
  const existing = (await store.read(mode)).proposals[id];
  if (existing && !["not_requested", "rejected", "write_failed"].includes(existing.status)) return existing; // idempotent

  if (mode === "live") {
    if (!env.AI_SEND_CONTENT_TO_OPENAI) throw new ServiceError("AI_SEND_CONTENT_TO_OPENAI=false: sending CMS content to OpenAI is not enabled for this deployment", 403, "ai_transfer_disabled");
    if (!opts.consentToSendContent) throw new ServiceError("Explicit consent to send this content item's title, current text and a short excerpt to OpenAI is required", 403, "consent_required");
  }
  const sg = finding.suggestion;
  const current = finding.current ?? "";
  const base: TranslationProposal = existing ?? {
    id, task: "seo", ruleId: finding.ruleId, issueId: finding.id, unitKey: seoUnitKey(finding.id),
    pointer: { hubId: "", contentTypeUid: finding.contentTypeUid, itemId: finding.itemId, locale: finding.locale, fieldPath: finding.fieldPath },
    status: "not_requested", provenance: mode === "live" ? "openai" : "simulated",
    sourceText: current, existingText: current, suggestedText: "",
    model: mode === "live" ? env.OPENAI_MODEL : "simulated-fixture", promptVersion: SEO_PROMPT_VERSION,
    sourceFingerprint: fingerprint(current), glossaryWarnings: [], placeholderWarnings: [], notes: [], updatedAt: new Date().toISOString(),
  };
  const fresh: TranslationProposal = { ...base, sourceText: current, existingText: current, sourceFingerprint: fingerprint(current) };
  let p = await step(mode, fresh, { type: "request" });

  const lengthNote = (text: string) => (text.length < sg.min || text.length > sg.max ? [`Length ${text.length} is outside the target ${sg.min}–${sg.max} characters.`] : [`Length ${text.length} characters (target ${sg.min}–${sg.max}).`]);
  try {
    if (mode === "demo") {
      const text = simulateSeoText({ target: sg.target, current, itemTitle: finding.title, excerpt: finding.excerpt ?? "", min: sg.min, max: sg.max });
      return step(mode, p, {
        type: "generated",
        patch: { suggestedText: text, provenance: "simulated", model: "simulated-fixture", notes: ["SIMULATED suggestion built by simple text rules — not generated by a model.", ...lengthNote(text)], costNote: "No model call in demo mode" },
      });
    }
    const { system, user } = buildSeoMessages({
      target: sg.target, locale: finding.locale, contentType: finding.contentTypeTitle, itemTitle: finding.title,
      currentText: current, problem: `${finding.message}. ${finding.evidence.join(" ")}`, excerpt: finding.excerpt ?? "", min: sg.min, max: sg.max,
    });
    const r = await requestStructured(env, { system, user, schemaName: "seo_text", jsonSchema: SEO_JSON_SCHEMA, zod: SeoOutputSchema });
    const usd = costFromUsage(env, r);
    return step(mode, p, {
      type: "generated",
      patch: {
        suggestedText: r.output.text.trim(), provenance: "openai", model: r.model, inputTokens: r.inputTokens, outputTokens: r.outputTokens,
        reasoningTokens: r.reasoningTokens, reasoningEffort: r.reasoningEffort, actualUsd: usd,
        costNote: usd === undefined ? "Not priced: set OPENAI_PRICE_INPUT_PER_MTOK / OPENAI_PRICE_OUTPUT_PER_MTOK to compute cost" : "Reported token usage × configured prices",
        notes: [...r.output.notes, ...lengthNote(r.output.text.trim())],
      },
    });
  } catch (err) {
    p = await findProposal(mode, id);
    const reason = err instanceof Error ? err.message : "Unknown error";
    await step(mode, p, { type: "generation_failed", reason });
    if (err instanceof AiError) throw new ServiceError(err.message, err.status, err.code);
    throw err;
  }
}
